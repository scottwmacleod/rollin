//! The TypeScript types for everything the Session sends the front end,
//! generated from the Rust types that are serialised (ADR-0007). The
//! checked-in `apps/desktop/src/api/generated.ts` must equal [`typescript`];
//! a test fails when it does not, and `just types` rewrites it.

use rollin::{CommandInfo, RollResult};
use std::any::TypeId;
use std::collections::HashSet;
use ts_rs::{Config, TypeVisitor, TS};

use crate::{About, Completions, ExecutionWire, State};

/// The roots: every type a Tauri command returns. Their dependencies follow.
fn visit_roots(v: &mut impl TypeVisitor) {
    v.visit::<ExecutionWire<'static>>();
    v.visit::<RollResult>();
    v.visit::<State>();
    v.visit::<Completions>();
    v.visit::<About>();
    v.visit::<CommandInfo>();
}

/// Collects each declaration once, dependencies before the types using them.
struct Declarations<'a> {
    cfg: &'a Config,
    seen: HashSet<TypeId>,
    out: Vec<(String, String)>,
}

impl TypeVisitor for Declarations<'_> {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        // Only types with a declaration of their own (not `string`, `Array`).
        if T::output_path().is_none() || !self.seen.insert(TypeId::of::<T>()) {
            return;
        }
        T::visit_dependencies(self);
        self.out.push((T::ident(self.cfg), T::decl(self.cfg)));
    }
}

/// The generated module's text.
pub fn typescript() -> String {
    // Integers the wire carries as JSON numbers, never `bigint`.
    let cfg = Config::new().with_large_int("number");
    let mut decls = Declarations {
        cfg: &cfg,
        seen: HashSet::new(),
        out: Vec::new(),
    };
    visit_roots(&mut decls);
    decls.out.sort();
    let mut text = String::from(
        "// Generated by `just types` from the Rust types in `rollin` and\n\
         // `rollin-desktop-core`; do not edit. Changing a serialised Rust field\n\
         // changes this file, and the `wire` test fails until it is regenerated.\n",
    );
    for (_, decl) in decls.out {
        text.push('\n');
        text.push_str(&format!("export {decl}\n"));
    }
    text
}
